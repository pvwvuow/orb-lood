#!/usr/bin/env bash
# ─────────────────────────────────────────────────────────────────────
# ORBLOOD — deploy / update the app on the VPS
#
# Usage (either works):
#   a) From an unzipped GitHub ZIP:
#        cd /tmp && unzip orb-lood-main.zip
#        sudo bash /tmp/orb-lood-main/deploy.sh
#   b) From a git checkout that IS the install dir:
#        cd /opt/orblood && sudo git pull && sudo bash deploy.sh
#
# What it does:
#   - Syncs new files into /opt/orblood (keeps server/.env, uploads and
#     node_modules; never deletes the folder it runs from)
#   - Makes sure server/.env has a safe JWT_SECRET (a published / weak one
#     is replaced automatically; users then log in once more)
#   - Installs npm dependencies, applies DB migrations (stops on failure)
#   - Busts the PWA cache
#   - Writes the systemd unit + nginx vhost only if they are missing or
#     were generated by this script (FORCE_SYSTEMD=1 / FORCE_NGINX=1 to
#     overwrite hand-edited ones)
#   - Restarts the backend and runs a smoke test
#
# Flags: SKIP_DB=1 (skip migrations), DOMAIN=orblood.ir
# ─────────────────────────────────────────────────────────────────────

set -euo pipefail

say()  { printf '\n\033[1;36m>> %s\033[0m\n' "$*"; }
warn() { printf '\033[1;33m!! %s\033[0m\n' "$*"; }
fail() { printf '\033[1;31m!! %s\033[0m\n' "$*"; exit 1; }
ok()   { printf '\033[1;32m✓  %s\033[0m\n' "$*"; }

[ "$(id -u)" = "0" ] || fail "Run as root: sudo bash deploy.sh"

# ── Config ──
INSTALL_DIR="${INSTALL_DIR:-/opt/orblood}"
APP_USER="orblood"
DOMAIN="${DOMAIN:-orblood.ir}"
SECRETS_FILE=/etc/orblood/secrets.env
MANAGED_MARK="# orblood-managed: deploy.sh"

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)"
mkdir -p "$INSTALL_DIR"
INSTALL_REAL="$(cd "$INSTALL_DIR" && pwd -P)"

[ -f "$SCRIPT_DIR/server/package.json" ] || fail "Cannot find server/package.json in $SCRIPT_DIR — run from the unzipped repo folder"
[ -f "$SCRIPT_DIR/public/index.html" ]   || fail "Cannot find public/index.html in $SCRIPT_DIR"

IN_PLACE=0
if [ "$SCRIPT_DIR" = "$INSTALL_REAL" ]; then
  IN_PLACE=1
else
  case "$SCRIPT_DIR/" in
    "$INSTALL_REAL"/*) fail "Source $SCRIPT_DIR is inside $INSTALL_REAL — move the unzipped folder elsewhere (e.g. /tmp)";;
  esac
  case "$INSTALL_REAL/" in
    "$SCRIPT_DIR"/*) fail "Install dir $INSTALL_REAL is inside the source folder $SCRIPT_DIR";;
  esac
fi

say "Deploying ORBLOOD from: $SCRIPT_DIR → $INSTALL_REAL"

# Hex sha256 of a string (for the leaked-secret check).
sha() { printf '%s' "$1" | sha256sum | awk '{print $1}'; }
LEAKED_JWT_SHA="344ba8eee178726136829d4f3cd818f6e13560818bb8a8ffe7a3f7aaa0037ad8"

set_kv() {
  local file="$1" key="$2" val="$3"
  touch "$file"
  python3 - "$file" "$key" "$val" <<'PY'
import sys, pathlib
path, key, val = sys.argv[1], sys.argv[2], sys.argv[3]
p = pathlib.Path(path)
out, done = [], False
for line in p.read_text().splitlines():
    if line.startswith(key + '='):
        if not done: out.append(f"{key}={val}")
        done = True
    else:
        out.append(line)
if not done: out.append(f"{key}={val}")
p.write_text('\n'.join(out) + '\n')
PY
}
get_kv() { [ -f "$1" ] && grep -E "^$2=" "$1" | tail -1 | cut -d= -f2- || true; }

command -v python3 >/dev/null || fail "python3 is required"

# ── Step 1: Sync files (no rm -rf of the install dir any more) ──
if [ "$IN_PLACE" = 1 ]; then
  ok "Running inside the install dir — files already in place"
else
  say "Syncing application files..."
  if ! command -v rsync >/dev/null; then
    apt-get install -y -qq rsync >/dev/null 2>&1 || true
  fi
  if command -v rsync >/dev/null; then
    rsync -a --delete \
      --exclude '/server/.env' \
      --exclude '/server/uploads/' \
      --exclude '/server/node_modules/' \
      --exclude '/node_modules/' \
      --exclude '/.git/' \
      --exclude '/dist-electron/' \
      "$SCRIPT_DIR/" "$INSTALL_REAL/"
  else
    warn "rsync not available — copying over the top (stale files are not removed)"
    cp -a "$SCRIPT_DIR/." "$INSTALL_REAL/"
  fi
  ok "Files synced"
fi

ENV_FILE="$INSTALL_REAL/server/.env"
mkdir -p "$INSTALL_REAL/server/uploads"

# ── Step 2: server/.env + secrets ──
mkdir -p /etc/orblood && chmod 700 /etc/orblood
touch "$SECRETS_FILE" && chmod 600 "$SECRETS_FILE"

if [ ! -f "$ENV_FILE" ]; then
  say "No server/.env yet — creating one"
  DB_PASSWORD_VAL="$(get_kv "$SECRETS_FILE" DB_PASSWORD)"
  [ -n "$DB_PASSWORD_VAL" ] || warn "DB_PASSWORD not in $SECRETS_FILE — set it in $ENV_FILE"
  cat > "$ENV_FILE" <<EOF
DB_HOST=127.0.0.1
DB_PORT=3306
DB_USER=orblood
DB_PASSWORD=${DB_PASSWORD_VAL}
DB_NAME=orblood
JWT_EXPIRES_IN=7d
HOST=127.0.0.1
PORT=4000
TRUST_PROXY=loopback
PUBLIC_ORIGIN=https://$DOMAIN
UPLOAD_DIR=./uploads
PUBLIC_UPLOADS_BASE=/uploads
TURN_HOST=turn.$DOMAIN
TURN_URLS=turn:turn.$DOMAIN:443?transport=tcp,turns:turn.$DOMAIN:443?transport=tcp
VOICE_FORCE_RELAY=true
EOF
  TS="$(get_kv "$SECRETS_FILE" TURN_SECRET)"
  [ -n "$TS" ] && set_kv "$ENV_FILE" TURN_SECRET "$TS"
  ok ".env created"
fi

# JWT_SECRET: keep a good one, replace a missing / weak / published one.
JWT="$(get_kv "$ENV_FILE" JWT_SECRET)"
if [ -z "$JWT" ] || [ "${#JWT}" -lt 32 ] || [ "$(sha "$JWT")" = "$LEAKED_JWT_SHA" ]; then
  CAND="$(get_kv "$SECRETS_FILE" JWT_SECRET)"
  if [ -n "$CAND" ] && [ "${#CAND}" -ge 32 ] && [ "$(sha "$CAND")" != "$LEAKED_JWT_SHA" ]; then
    JWT="$CAND"
  else
    JWT="$(openssl rand -hex 48 2>/dev/null || python3 -c 'import secrets;print(secrets.token_hex(48))')"
    set_kv "$SECRETS_FILE" JWT_SECRET "$JWT"
  fi
  set_kv "$ENV_FILE" JWT_SECRET "$JWT"
  warn "JWT_SECRET was missing or the published value — replaced. Everyone logs in once more."
else
  # Keep secrets.env in sync so a lost .env can be rebuilt.
  [ -n "$(get_kv "$SECRETS_FILE" JWT_SECRET)" ] || set_kv "$SECRETS_FILE" JWT_SECRET "$JWT"
  ok "JWT_SECRET ok"
fi

# Safe network defaults for this layout (nginx in front on the same box).
[ -n "$(get_kv "$ENV_FILE" HOST)" ]        || set_kv "$ENV_FILE" HOST 127.0.0.1
[ -n "$(get_kv "$ENV_FILE" TRUST_PROXY)" ] || set_kv "$ENV_FILE" TRUST_PROXY loopback

if [ -n "$(get_kv "$ENV_FILE" TURN_PASSWORD)" ] && [ -z "$(get_kv "$ENV_FILE" TURN_SECRET)" ]; then
  warn "TURN still uses a static password. Run: sudo bash $INSTALL_REAL/scripts/rotate-secrets.sh"
fi

# ── Step 3: Permissions ──
say "Setting permissions..."
id "$APP_USER" >/dev/null 2>&1 || useradd --system --create-home --shell /usr/sbin/nologin "$APP_USER"
chown -R "$APP_USER:$APP_USER" "$INSTALL_REAL/server" "$INSTALL_REAL/public"
chmod 600 "$ENV_FILE"
chmod +x "$INSTALL_REAL"/scripts/*.sh "$INSTALL_REAL"/deploy.sh 2>/dev/null || true
ok "Permissions set"

# ── Step 4: npm dependencies ──
say "Installing npm dependencies..."
cd "$INSTALL_REAL/server"
if sudo -u "$APP_USER" npm install --omit=dev --no-audit --no-fund 2>&1 | tail -3; then
  ok "Dependencies installed"
else
  if [ -d node_modules ]; then
    warn "npm install failed — keeping the existing node_modules (no new deps were added)"
  else
    fail "npm install failed and there is no node_modules — check network / npm mirror"
  fi
fi

# ── Step 5: DB migrations (fail closed) ──
if [ "${SKIP_DB:-0}" = "1" ]; then
  warn "SKIP_DB=1 — not touching the database (the server also migrates on start)"
else
  say "Applying database migrations (idempotent, data preserved)..."
  if sudo -u "$APP_USER" npm run --silent init-db; then
    ok "Schema up to date"
  else
    fail "init-db failed — fix DB credentials in $ENV_FILE and re-run (or SKIP_DB=1)"
  fi
fi

# ── Step 5b: frontend safety patches (exact-match, see scripts/patch-frontend.mjs) ──
if [ "$IN_PLACE" = 1 ] && [ -d "$INSTALL_REAL/.git" ]; then
  warn "git checkout install: not patching app.js in place (would block the next git pull)."
  warn "Run scripts/patch-frontend.mjs on your PC, commit the result, or deploy from the ZIP."
else
  say "Applying frontend safety patches..."
  node "$INSTALL_REAL/scripts/patch-frontend.mjs" "$INSTALL_REAL/public/js/app.js" || warn "frontend patches not applied"
  chown "$APP_USER:$APP_USER" "$INSTALL_REAL/public/js/app.js" 2>/dev/null || true
fi

# ── Step 6: Bust PWA cache ──
SW_FILE="$INSTALL_REAL/public/sw.js"
if [ -f "$SW_FILE" ]; then
  STAMP="v$(date +%Y%m%d%H%M%S)"
  sed -i "s/const CACHE_NAME = '[^']*'/const CACHE_NAME = 'orblood-shell-$STAMP'/" "$SW_FILE"
  chown "$APP_USER:$APP_USER" "$SW_FILE"
  ok "PWA cache busted → orblood-shell-$STAMP"
fi

# A file is "ours" if it carries our marker or is the old generated one.
is_managed() {
  [ ! -f "$1" ] && return 0
  grep -qF "$MANAGED_MARK" "$1" && return 0
  grep -qF "$2" "$1" && return 0
  return 1
}

# ── Step 7: systemd unit ──
UNIT=/etc/systemd/system/orblood.service
DB_UNIT="mariadb.service"
systemctl list-unit-files mariadb.service >/dev/null 2>&1 && systemctl list-unit-files mariadb.service | grep -q mariadb \
  || DB_UNIT="mysql.service"
if [ "${FORCE_SYSTEMD:-0}" = "1" ] || is_managed "$UNIT" "Description=Orblood backend"; then
  say "Writing systemd unit..."
  cat > "$UNIT" <<EOF
$MANAGED_MARK
[Unit]
Description=Orblood backend
After=network.target $DB_UNIT
Wants=$DB_UNIT

[Service]
Type=simple
User=$APP_USER
WorkingDirectory=$INSTALL_REAL/server
EnvironmentFile=$INSTALL_REAL/server/.env
ExecStart=/usr/bin/env node src/index.js
Restart=always
RestartSec=3
KillSignal=SIGTERM
TimeoutStopSec=15
StandardOutput=journal
StandardError=journal
NoNewPrivileges=true
ProtectSystem=strict
ProtectHome=true
ReadWritePaths=$INSTALL_REAL/server/uploads
PrivateTmp=true

[Install]
WantedBy=multi-user.target
EOF
  systemctl daemon-reload
  systemctl enable orblood >/dev/null 2>&1
  ok "systemd unit configured"
else
  warn "$UNIT was edited by hand — left as is (FORCE_SYSTEMD=1 to replace)"
fi

# ── Step 8: nginx ──
if command -v nginx >/dev/null; then
  say "Configuring nginx..."
  mkdir -p /etc/nginx/snippets /etc/nginx/conf.d
  # http-level: a log format WITHOUT query strings (the WebSocket token
  # travels in ?token=, it must never land in access logs).
  cat > /etc/nginx/conf.d/orblood-logformat.conf <<'EOF'
# orblood-managed: deploy.sh
log_format orblood_noargs '$remote_addr - [$time_local] "$request_method $uri $server_protocol" '
                          '$status $body_bytes_sent "$http_user_agent" $request_time';
EOF
  cat > /etc/nginx/snippets/orblood-headers.conf <<'EOF'
# orblood-managed: deploy.sh — included in every location that sets headers
add_header X-Content-Type-Options "nosniff" always;
add_header Referrer-Policy "strict-origin-when-cross-origin" always;
add_header X-Frame-Options "SAMEORIGIN" always;
add_header Permissions-Policy "microphone=(self), camera=(), geolocation=()" always;
EOF
  # Real visitor IP behind ArvanCloud (+ weekly refresh).
  bash "$INSTALL_REAL/scripts/arvan-realip.sh" || warn "Arvan IP list not refreshed (offline?)"
  cat > /etc/cron.weekly/orblood-arvan-realip <<EOF
#!/bin/sh
bash $INSTALL_REAL/scripts/arvan-realip.sh >/dev/null 2>&1 || true
EOF
  chmod 755 /etc/cron.weekly/orblood-arvan-realip

  VHOST=/etc/nginx/sites-available/orblood
  if [ "${FORCE_NGINX:-0}" = "1" ] || is_managed "$VHOST" "No cache for HTML/JS/CSS"; then
    cat > "$VHOST" <<EOF
$MANAGED_MARK
server {
    listen 80;
    listen [::]:80;
    server_name $DOMAIN www.$DOMAIN;

    root $INSTALL_REAL/public;
    index index.html;
    client_max_body_size 8m;
    server_tokens off;
    access_log /var/log/nginx/orblood.access.log orblood_noargs;

    include snippets/orblood-headers.conf;
    # Optional: injects the CDN-bypass WebSocket URL (fix-arvan-ws.sh).
    include snippets/orblood-realtime*.conf;

    # Design sample pages are not part of the product.
    location ~ ^/(modal-samples|notification-previews)\.html\$ { return 404; }

    # Service worker + HTML: always revalidate (new deploys show up at once)
    location = /sw.js {
        include snippets/orblood-headers.conf;
        add_header Cache-Control "no-cache, no-store, must-revalidate" always;
        try_files \$uri =404;
    }
    location ~* \.(html|js|css|webmanifest)\$ {
        include snippets/orblood-headers.conf;
        add_header Cache-Control "no-cache, must-revalidate" always;
        try_files \$uri \$uri/ /index.html;
    }

    location / {
        try_files \$uri \$uri/ /index.html;
    }

    location /api/ {
        proxy_pass         http://127.0.0.1:4000/api/;
        proxy_http_version 1.1;
        proxy_set_header   Host              \$host;
        # \$remote_addr is the real visitor (real_ip module, Arvan list).
        # Overwrite, never append: clients must not inject their own hops.
        proxy_set_header   X-Real-IP         \$remote_addr;
        proxy_set_header   X-Forwarded-For   \$remote_addr;
        proxy_set_header   X-Forwarded-Proto https;
        proxy_read_timeout 60s;
    }

    location /ws {
        proxy_pass         http://127.0.0.1:4000/ws;
        proxy_http_version 1.1;
        proxy_set_header   Upgrade           \$http_upgrade;
        proxy_set_header   Connection        "upgrade";
        proxy_set_header   Host              \$host;
        proxy_set_header   X-Real-IP         \$remote_addr;
        proxy_set_header   X-Forwarded-For   \$remote_addr;
        proxy_buffering    off;
        proxy_read_timeout 1d;
        proxy_send_timeout 1d;
    }

    # Uploaded images: served from disk, never executable as a page.
    location /uploads/ {
        alias $INSTALL_REAL/server/uploads/;
        include snippets/orblood-headers.conf;
        add_header Content-Security-Policy "default-src 'none'; img-src 'self' data:; sandbox" always;
        add_header Cache-Control "public, max-age=604800" always;
        types { image/png png; image/jpeg jpg jpeg; image/gif gif; image/webp webp; }
        default_type application/octet-stream;
    }
}
EOF
    ln -sf "$VHOST" /etc/nginx/sites-enabled/orblood
    rm -f /etc/nginx/sites-enabled/default
    ok "nginx vhost written"
  else
    warn "$VHOST was edited by hand — left as is (FORCE_NGINX=1 to replace)"
  fi
  if nginx -t 2>/dev/null; then
    systemctl reload nginx
    ok "nginx reloaded"
  else
    nginx -t || true
    warn "nginx config test failed — fix it, then: systemctl reload nginx"
  fi
fi

# ── Step 9: Restart backend ──
say "Restarting orblood..."
systemctl restart orblood
sleep 2
systemctl is-active --quiet orblood && ok "orblood is running" || warn "orblood failed — journalctl -u orblood -n 30"

# ── Step 10: Smoke test ──
HEALTH=$(curl -sf --max-time 5 http://127.0.0.1:4000/api/healthz 2>/dev/null || echo "FAIL")
if echo "$HEALTH" | grep -q '"ok":true'; then
  ok "API healthy: $HEALTH"
else
  warn "Health check failed: $HEALTH — journalctl -u orblood -n 30 --no-pager"
fi

echo
printf '\033[1;32m═══════════════════════════════════════════════════\033[0m\n'
printf '\033[1;32m  DEPLOY COMPLETE\033[0m\n'
printf '\033[1;32m═══════════════════════════════════════════════════\033[0m\n'
echo
echo "  Site:    https://$DOMAIN"
echo "  Status:  systemctl status orblood"
echo "  Logs:    journalctl -u orblood -f"
echo "  Voice:   sudo bash $INSTALL_REAL/scripts/setup-voice.sh diagnose"
echo
